const { chromium } = require('playwright');
const path = require('path'); const OUT = process.env.E2E_OUT || require('os').tmpdir(), URL = process.env.E2E_URL || 'http://localhost:8599', EX = path.join(__dirname, '..', '..', 'exemplos') + '/';
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
  const erros = []; page.on('pageerror', e => erros.push(String(e)));
  const esperar = async () => { await page.waitForTimeout(700); await page.waitForSelector('[data-testid="stStatusWidget"]', { state: 'detached', timeout: 20000 }).catch(() => {}); await page.waitForTimeout(500); };
  const exc = async (onde) => { if (await page.locator('[data-testid="stException"]').count()) throw new Error(onde + ': ' + await page.locator('[data-testid="stException"]').first().innerText()); };
  const alerta = async () => (await page.locator('[data-testid="stAlert"]').allInnerTexts()).join(' | ').slice(0, 400);
  const ir = async (n) => { await page.getByRole('link', { name: n }).click(); await esperar(); await exc(n); };
  const subir = async (rot, f) => { await page.locator('[data-testid="stFileUploader"]').filter({ hasText: rot }).locator('input[type=file]').setInputFiles(f); await esperar(); };
  await page.goto(URL); await esperar();
  await page.screenshot({ path: `${OUT}/20_setup.png` });
  await page.getByLabel('Nome do administrador').fill('Admin Teste');
  await page.getByLabel('E-mail (login)').fill('adm@teste.test');
  await page.getByLabel('Senha (mín. 8)').fill('senha-123');
  await page.getByLabel('Razão social da primeira empresa').fill('Gama Ltda');
  await page.getByLabel('CNPJ').fill('33.333.333/0001-33');
  await page.getByLabel('Identificador da pasta (ex.: alfa-servicos)').fill('gama');
  await page.getByRole('button', { name: 'Criar' }).click(); await esperar(); await exc('setup');
  console.log('1.', await alerta());
  await page.getByLabel('E-mail').fill('adm@teste.test'); await page.getByLabel('Senha').fill('senha-123');
  await page.getByRole('button', { name: 'Entrar' }).click(); await esperar(); await exc('login');
  await ir('Cadastros');
  await subir('Plano de contas do Fortes', EX + 'plano_contas_fortes.csv');
  await page.getByRole('button', { name: 'Importar plano' }).click(); await esperar(); await exc('plano');
  console.log('2.', await alerta());
  await page.locator('[data-testid=\"stButtonGroup\"]').getByText('Regras').first().click(); await esperar();
  await subir('Importar regras', EX + 'regras_exemplo.json');
  await page.getByRole('button', { name: 'Importar regras' }).click(); await esperar(); await exc('regras');
  console.log('3.', await alerta());
  await ir('Cargas');
  await page.getByLabel('Conta do banco no plano (reduzido)').click(); await page.keyboard.type('362'); await page.keyboard.press('Enter'); await esperar();
  await subir('Extrato', EX + 'extrato_exemplo.csv');
  await page.screenshot({ path: `${OUT}/21_mapeamento.png`, fullPage: true });
  await page.getByRole('button', { name: 'Validar e carregar extrato' }).click(); await esperar(); await exc('carga csv');
  console.log('4.', await alerta());
  await page.getByLabel('Conta do banco no plano (reduzido)').click(); await page.keyboard.type('362'); await page.keyboard.press('Enter'); await esperar();
  await subir('Extrato', EX + 'extrato_exemplo.csv');
  await page.getByRole('button', { name: 'Validar e carregar extrato' }).click(); await esperar(); await exc('carga repetida');
  console.log('5.', await alerta());
  await page.screenshot({ path: `${OUT}/22_repetido.png` });
  await ir('Sessão');
  await page.screenshot({ path: `${OUT}/23_sessao_admin.png`, fullPage: true });
  await browser.close();
  console.log('erros JS:', erros);
})().catch(e => { console.error('FALHA', e.message); process.exit(1); });
